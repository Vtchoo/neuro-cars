require('./splines.cjs');
const assert=require('node:assert/strict');
const THREE=require('three');
const {Heightmap}=require('../src/maps/Heightmap.ts');
const Track=require('../src/Track.ts').default;
const Track3d=require('../src/renderers/3d/Track3d.ts').default;
const Car3d=require('../src/renderers/3d/Car3d.ts').default;
const {Helicopter3d}=require('../src/renderers/3d/Helicopter3d.ts');
const {Effects}=require('../src/core/Effects.ts');
const Game=require('../src/core/Game.ts').default;
const field=new Heightmap({version:1,width:2,height:2,widthMeters:100,heightMeters:100,originX:0,originY:0,datumMeters:0},[700,710,730,740]);
assert.equal(field.worldHeight(-250,-250),0);
assert.equal(field.worldHeight(250,250),400);
assert.equal(field.worldHeight(0,0),200);
const data={startingPoint:{x:-400,y:0},startingDirection:0,closed:false,pieces:[{type:'Spline',start:{x:-400,y:0},control1:{x:-150,y:0},control2:{x:150,y:0},end:{x:400,y:0},width:100}]};
const track=Track3d.fromData(data);
const lengths=track.cumulativeLengths.slice();track.setHeightmap(field);
assert.equal(track.pieces[0].start.elevation,715);
assert.equal(track.pieces[0].end.elevation,725);
assert.deepEqual(track.cumulativeLengths,lengths,'Height assignment leaves 2D distances unchanged');
const scene=new THREE.Scene();track.render(scene);
const bounds=new THREE.Box3().setFromObject(track.object);
assert.ok(bounds.max.y>250 && bounds.min.y>100,'Road and curbs follow elevated terrain');
const loaded=Track3d.fromData(track.exportData());
assert.equal(loaded.pieces[0].control1.elevation,track.pieces[0].control1.elevation);
assert.deepEqual(loaded.heightmap.toData(),field.toData());
const car=new Car3d(0,0,0);car.lastLookAheadPoints=[{x:200,y:0}];
car.render(scene,undefined,true,(x,y)=>track.getWorldHeight(x,y));
assert.equal(car.object.position.y,200);assert.deepEqual({x:car.pos.x,y:car.pos.y},{x:0,y:0});
const heli=new Helicopter3d(0),state=new Effects().helicopters[0];
Object.assign(state,{x:0,y:0,altitude:2000,targetX:200,targetY:0,heading:1,bank:.2});
heli.update(state,16/9,(x,y)=>track.getWorldHeight(x,y));
assert.equal(heli.object.position.y,2200,'Helicopter flight altitude is relative to the local ground');
const origin=heli.camera.getWorldPosition(new THREE.Vector3()),direction=heli.camera.getWorldDirection(new THREE.Vector3());
assert.ok(direction.dot(new THREE.Vector3(200,track.getWorldHeight(200,0)+4,0).sub(origin).normalize())>1-1e-10,'Gimbal aims at the elevated target');
function exercise(elevated) {
    const game=new Game(42);game.track=Track.fromData(data);if(elevated)game.track.setHeightmap(field);
    game.start.x=-400;game.setupPopulation(4);game.maxTicks=10000;game.cycleStartPoint='off';game.performClusteringAnalysis=()=>{};
    for(let i=0;i<180;i++)game.step();
    return game;
}
const baseline=exercise(false),raised=exercise(true);
assert.deepEqual(raised.exportState().population,baseline.exportState().population,'Heightmaps do not change motion, fitness, breeding or neural nets');
const save=raised.exportState(),restored=new Game(42);restored.restoreGameState(save);
assert.deepEqual(restored.track.heightmap.toData(),field.toData());
const previousHeightmap=restored.track.heightmap;
restored.setPhase('resetTrack');assert.equal(restored.track.heightmap,previousHeightmap,'Resetting the editor retains the active map elevation');
car.dispose();heli.dispose();track.dispose();loaded.dispose();
console.log('Passed elevation baseline, node sampling, 3D roads/cars, ground-relative helicopters, game-save restoration, and unchanged 2D simulation.');
